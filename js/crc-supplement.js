  function rxLine(head, sub, items) {
    return '<div class="rx-line"><div class="rx-line-h"><span class="rx-h">' + head + '</span>' +
      (sub ? '<span class="rx-sub">' + sub + '</span>' : '') + '</div>' +
      '<ul class="rx-items"><li>' + items.join('</li><li>') + '</li></ul></div>';
  }

  /* 一個補充主題 ＝ 一個可折疊面板；預設全部收合，避免壓過院內流程圖 */
  function panel(summary, title, src, inner) {
    return '<details><summary>' + summary + '</summary>' +
      '<div class="rec-detail rx-panel">' +
      '<div class="rx-panel-h">' + title + '<span class="rx-panel-src">' + (src || SRC) + '</span></div>' +
      inner + '</div></details>';
  }

  function table(head, rows) {
    var h = '<div class="crc-supp-scroll"><table><thead><tr><th>' + head.join('</th><th>') +
      '</th></tr></thead><tbody>';
    rows.forEach(function (row) { h += '<tr><td>' + row.join('</td><td>') + '</td></tr>'; });
    return h + '</tbody></table></div>';
  }

